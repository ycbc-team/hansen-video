# -*- coding: utf-8 -*-
import csv, json, re
from collections import Counter
from extra_entries import ADD

base = [tuple(r) for r in json.load(open("互动点库.json", encoding="utf-8"))]
seen = set((r[0], r[1]) for r in base)
new = [r for r in ADD if (r[0], r[1]) not in seen]

D = base + new
def key(r):
    m, d = re.match(r"(\d+)月(\d+)日", r[0]).groups()
    return (int(m), int(d))
D.sort(key=key)

# 同一天内保持手工顺序稳定（sorted 稳定排序即可）

with open("互动点库.csv", "w", newline="", encoding="utf-8-sig") as f:
    w = csv.writer(f)
    w.writerow(["日期", "选题", "类型", "剧情/钩子", "画面要点", "建议镜数"])
    for r in D:
        w.writerow(r)

