# -*- coding: utf-8 -*-
"""从 260 条里筛出真正有拍摄亮点的，并排优先级；时长按镜数给区间，不再强绑 60 秒。"""
import csv, json
from collections import Counter

D = json.load(open("互动点库.json", encoding="utf-8"))  # 260 条，顺序固定
assert len(D) == 260

# ---- 剔除：无画面 / 纯数据 / 同主题重复 / 医疗复诊 / 纯家务流程 ----
DROP = [
1,5,6,7,10,11,13,19,23,26,29,34,36,38,43,45,47,50,54,55,
57,61,63,64,67,69,70,72,74,75,78,81,82,86,88,89,93,101,108,109,
111,113,115,116,119,123,128,129,134,138,140,142,146,147,148,151,153,154,156,158,
161,162,163,168,171,175,176,179,180,182,184,186,189,195,205,206,208,212,213,214,
216,221,224,225,235,237,240,244,246,252,253,257,260,
]

# ---- P0 首发：一镜成立、笑点/反差最强，起号先拍 ----
P0 = [8,15,16,17,18,44,59,71,77,92,107,137,141,149,164,165,
      172,177,187,191,193,199,200,210,217,219,223,232,233,249,251,258]

# ---- P1 好拍：画面清楚，但要一到两句铺垫 ----
P1 = [3,12,20,22,27,30,31,33,37,40,42,46,49,52,53,58,65,66,68,76,
      80,83,84,85,87,90,91,94,98,100,106,110,112,114,117,121,124,125,127,132,
      133,136,143,144,145,152,159,160,167,169,170,174,178,181,185,188,197,198,202,204,
      209,211,215,218,220,226,227,228,238,239,242,243,250,254,255]

dropset, p0, p1 = set(DROP), set(P0), set(P1)
assert not (p0 & p1)
assert p0 <= set(range(1, 261)) and p1 <= set(range(1, 261))

keep = [i for i in range(1, 261) if i not in dropset]
for i in p0 | p1:
    assert i in keep, i

DUR = {1: "15–25秒", 2: "25–40秒", 3: "40–55秒"}
TIER = {}
for i in keep:
    TIER[i] = "P0 首发" if i in p0 else ("P1 好拍" if i in p1 else "P2 备选")

order = ["P0 首发", "P1 好拍", "P2 备选"]
rows = []
n = 0
for t in order:
    for i in keep:
        if TIER[i] != t:
            continue
        n += 1
        r = D[i - 1]
        rows.append([n, t, r[0], r[1], r[2], DUR[r[5]], r[5], r[3], r[4]])

with open("互动点库.csv", "w", newline="", encoding="utf-8-sig") as f:
    w = csv.writer(f)
    w.writerow(["序号", "优先级", "日期", "选题", "类型", "建议时长", "镜数", "剧情/钩子", "画面要点"])
    w.writerows(rows)

tc = Counter(r[1] for r in rows)
ty = Counter(r[4] for r in rows)

L = ["# 瀚森投喂日记 · 互动点库（精选版）", "",
     f"从日记原稿抽出 260 条候选，按「有没有真实画面亮点」砍掉 {len(DROP)} 条，"
     f"保留 **{len(rows)} 条**，并按拍摄优先级排好序。", "",
     "## 怎么用这张表", "",
     "- **排序 = 开机顺序**：P0 先拍，P1 接着拍，P2 当备胎；同一层级内按日记时间排，方便找素材",
     "- **时长跟着剧情走**，不再强绑 60 秒：1 镜 15–25 秒、2 镜 25–40 秒、3 镜 40–55 秒",
     "  （单镜 2–4 秒是模型上限，不是审美选择；剧情只需要一个转折的，就不要硬凑到 60 秒）",
     "- **类型**：搞笑 / 成长 / 温情 / 共鸣 / 干货 / 翻车", "",
     "## 优先级分布", "",
     "| 层级 | 条数 | 判断标准 |", "|---|---|---|",
     f"| P0 首发 | {tc['P0 首发']} | 一镜成立或一句台词就成立，笑点/反差最强，不用铺陈 |",
     f"| P1 好拍 | {tc['P1 好拍']} | 画面清楚，但要 1–2 句铺垫或一个反应镜头 |",
     f"| P2 备选 | {tc['P2 备选']} | 有亮点但偏弱，或与同主题条目撞车，留着换口味 |", "",
     f"类型分布：{' / '.join(f'{k} {v}' for k, v in ty.most_common())}", "",
     "## 砍掉的 93 条是什么", "",
     "- **纯数据**：涨了多少克、喝到多少毫升、睡了几个小时——没有画面，只有数字",
     "- **同主题重复**：翻身/爬行/撅屁股/尖叫/生物钟各出现四五次，只留最强的",
     "- **无画面**：护士投诉、全家等便便、育儿观念讨论——观众看不到东西",
     "- **医疗复诊**：耳朵矫正复查、疫苗反应、疹子处理——不合'有趣'定位，也有合规风险",
     "- **纯流程**：换尿布、做辅食、冲奶——说明性太强，没有冲突", ""]

names = {"P0 首发": "P0 · 首发 32 条（这周就能开机）",
         "P1 好拍": f"P1 · 好拍 {tc['P1 好拍']} 条（首发跑通后接上）",
         "P2 备选": f"P2 · 备选 {tc['P2 备选']} 条（换口味用）"}
for t in order:
    sub = [r for r in rows if r[1] == t]
    L += ["", f"## {names[t]}", "",
          "| # | 日期 | 选题 | 类型 | 时长 | 镜数 | 剧情 / 钩子 | 画面要点 |",
          "|---|---|---|---|---|---|---|---|"]
    for r in sub:
        L.append(f"| {r[0]} | {r[2]} | {r[3]} | {r[4]} | {r[5]} | {r[6]} | {r[7]} | {r[8]} |")
L.append("")
open("互动点库.md", "w", encoding="utf-8").write("\n".join(L))
json.dump(rows, open("互动点库_精选.json", "w", encoding="utf-8"), ensure_ascii=False, indent=1)

print("kept:", len(rows), "dropped:", len(DROP))
print("tiers:", tc.most_common())
print("types:", ty.most_common())
print("dur:", Counter(r[5] for r in rows).most_common())
print("md chars:", len(open("互动点库.md", encoding="utf-8").read()))
