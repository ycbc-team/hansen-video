TYPE_W = {'搞怪动作': 3.0, '成长节点': 2.6, '家庭关系': 2.0, '温情': 1.2}
VIS_W  = {'强': 2.0, '中': 1.0, '弱': 0.0}
DUR_W  = {'15–25秒': 1.0, '25–40秒': 0.3, '40–55秒': -0.5}
BAO_W  = {'S': 3.0, 'A': 2.0, 'B': 1.0}
DAY_W  = {'P0': 1.2, 'P1': 0.5, 'P2': 0.0}

rows = []
for e in d['bao']:
    no, grade, date, title, typ, dur, why, shot = e
    cat, vis = CLS[no]
    score = TYPE_W[cat]*2 + VIS_W[vis] + DUR_W.get(dur, 0) + BAO_W[grade]
    rows.append(dict(no=no, pool='爆款池', old=grade, date=date, title=title,
                     cat=cat, vis=vis, dur=dur, shot=shot, why=why, score=round(score, 1)))
for e in d['daily']:
    no, date, title, typ, dur, shot, grade = e
    cat, vis = CLS[no]
    score = TYPE_W[cat]*2 + VIS_W[vis] + DUR_W.get(dur, 0) + DAY_W[grade]
    rows.append(dict(no=no, pool='日常池', old=grade, date=date, title=title,
                     cat=cat, vis=vis, dur=dur, shot=shot, why='', score=round(score, 1)))

def grade(s):
    if s >= 11.5: return 'S+'
    if s >= 10.0: return 'S'
    if s >= 8.5:  return 'A'
    if s >= 7.0:  return 'B'
    return 'C'

for r in rows:
    r['new'] = grade(r['score'])

# 爆款表：原爆款池里重评仍 >= A 的保留；掉到 B/C 的降级进入日常
bao_keep = [r for r in rows if r['pool'] == '爆款池' and r['new'] in ('S+', 'S', 'A')]
bao_drop = [r for r in rows if r['pool'] == '爆款池' and r['new'] in ('B', 'C')]
rest     = [r for r in rows if r['pool'] == '日常池'] + bao_drop

bao_keep.sort(key=lambda r: (-r['score'], r['no']))
rest.sort(key=lambda r: (-r['score'], r['no']))
